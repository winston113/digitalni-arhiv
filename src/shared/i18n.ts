export type Key = keyof typeof EN;

export function tr(lang: Lang, text: string): string {
  return lang === 'en' && Object.hasOwn(EN, text) ? EN[text as Key] : text;
}

// Zamenjava s funkcijo, da se znaki, kot je $&, v vrednostih ne obravnavajo posebej.
export function translate(lang: Lang, key: Key, params: Params = {}): string {
  return tr(lang, key).replace(/\{(\w+)\}/g, (match, name: string) => (Object.hasOwn(params, name) ? String(params[name]) : match));
}
